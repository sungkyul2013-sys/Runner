export type StringKey = keyof typeof STRINGS;

// §18.6: Korean is the default language; the settings (or `?lang=en` for a test page) switch it.
function initialLang(): Lang {
  const q = new URLSearchParams(globalThis.location?.search ?? '').get('lang');
  if (q === 'en' || q === 'ko') return q;
  try {
    const stored = JSON.parse(globalThis.localStorage?.getItem('apex.settings.v1') ?? 'null') as { lang?: string } | null;
    if (stored?.lang === 'en') return 'en';
  } catch {
    // storage blocked or unreadable: Korean
  }
  return 'ko';
}
let lang: Lang = initialLang();

export function setLang(l: Lang): void {
  lang = l;
}
export function currentLang(): Lang {
  return lang;
}
export function t(key: StringKey): string {
  return STRINGS[key][lang];
}
export function tl(text: Localized): string {
  return text[lang];
}
